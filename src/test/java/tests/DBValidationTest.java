package tests;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

import org.testng.Assert;
import org.testng.annotations.BeforeClass;
import org.testng.annotations.Test;
import utils.DBUtils;

/**
 * Database validation: the data must stay consistent regardless of what the UI or the API say.
 *
 * The test owns its data: it creates the tables and seeds them before the class runs, so it does
 * not depend on anything left behind by other tests or by a shared environment.
 * The queries are the same reconciliation checks used against a real payments database.
 */
public class DBValidationTest {

    @BeforeClass(groups = {"DB"})
    public void seedDatabase() throws SQLException {
        try (Connection conn = DBUtils.getConnection();
             Statement stmt = conn.createStatement()) {
            stmt.execute("DROP TABLE IF EXISTS transactions");
            stmt.execute("DROP TABLE IF EXISTS cards");
            stmt.execute("CREATE TABLE cards ("
                    + "card_id VARCHAR(20) PRIMARY KEY, "
                    + "status VARCHAR(10) NOT NULL, "
                    + "balance DECIMAL(10,2) NOT NULL)");
            stmt.execute("CREATE TABLE transactions ("
                    + "id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
                    + "card_id VARCHAR(20) NOT NULL, "
                    + "type VARCHAR(20) NOT NULL, "
                    + "amount DECIMAL(10,2) NOT NULL)");
            stmt.execute("INSERT INTO cards (card_id, status, balance) VALUES "
                    + "('CARD-1', 'ACTIVE', 50.00), "
                    + "('CARD-2', 'ACTIVE', 20.00), "
                    + "('CARD-3', 'INACTIVE', 0.00)");
            stmt.execute("INSERT INTO transactions (card_id, type, amount) VALUES "
                    + "('CARD-1', 'ACTIVATION', 50.00), "
                    + "('CARD-2', 'ACTIVATION', 20.00)");
        }
    }

    @Test(groups = {"DB"})
    public void everyActiveCardHasAnActivation() throws SQLException {
        String sql = "SELECT c.card_id FROM cards c "
                + "LEFT JOIN transactions t ON t.card_id = c.card_id AND t.type = 'ACTIVATION' "
                + "WHERE c.status = 'ACTIVE' AND t.id IS NULL";
        Assert.assertEquals(countRows(sql), 0, "Active cards without an activation transaction");
    }

    @Test(groups = {"DB"})
    public void noCardHasDuplicateActivations() throws SQLException {
        String sql = "SELECT card_id FROM transactions "
                + "WHERE type = 'ACTIVATION' GROUP BY card_id HAVING COUNT(*) > 1";
        Assert.assertEquals(countRows(sql), 0, "Cards with more than one activation");
    }

    @Test(groups = {"DB"})
    public void balanceMatchesTransactions() throws SQLException {
        String sql = "SELECT c.card_id FROM cards c "
                + "JOIN transactions t ON t.card_id = c.card_id "
                + "GROUP BY c.card_id, c.balance HAVING c.balance <> SUM(t.amount)";
        Assert.assertEquals(countRows(sql), 0, "Cards whose balance differs from the sum of their transactions");
    }

    private int countRows(String sql) throws SQLException {
        try (Connection conn = DBUtils.getConnection();
             PreparedStatement stmt = conn.prepareStatement(sql);
             ResultSet rs = stmt.executeQuery()) {
            int rows = 0;
            while (rs.next()) {
                rows++;
            }
            return rows;
        }
    }
}
